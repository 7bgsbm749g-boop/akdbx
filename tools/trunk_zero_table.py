"""Print akdbx's TRUNK_ZERO table from Google's libphonenumber metadata.

Development tool only; akdbx does not import it or depend on phonenumbers.
Run it in a scratch venv: ``pip install phonenumbers==9.0.19`` and then
``python tools/trunk_zero_table.py``. A country calling code is listed only when
every region that shares it meets all of these rules:

* the national (trunk) prefix is exactly ``0``;
* no national significant number can begin with ``0`` (so the ``0`` is never
  part of the number, as it is in Italy);
* no other prefix-for-parsing rule (carrier selection, a mobile token) can read
  a value that begins with ``0``, apart from fixed-length local-dialling rules
  that no full national number can match;
* ``0`` + the national significant number of every example number parses back
  to that number and is valid.

The listed lengths are the possible lengths of a national significant number
that fit E.164 (15 digits at most with the calling code).
"""
try:
    import re._constants as sc
    import re._parser as sp
except ImportError:  # Python < 3.11
    import sre_constants as sc
    import sre_parse as sp

import phonenumbers
from phonenumbers import COUNTRY_CODE_TO_REGION_CODE, PhoneMetadata, PhoneNumberType

TYPES = [getattr(PhoneNumberType, name) for name in (
    'FIXED_LINE', 'MOBILE', 'TOLL_FREE', 'PREMIUM_RATE', 'SHARED_COST', 'VOIP', 'PERSONAL_NUMBER', 'PAGER', 'UAN',
    'VOICEMAIL')]


def first(items):
    """The characters a parsed pattern can begin with, and whether it can match nothing."""
    chars = set()
    for op, av in items:
        found, empty = first_op(op, av)
        chars |= found
        if not empty:
            return chars, False
    return chars, True


def first_op(op, av):
    if op is sc.LITERAL:
        return {chr(av)}, False
    if op is sc.IN:
        chars = set()
        for kind, arg in av:
            if kind is sc.LITERAL:
                chars.add(chr(arg))
            elif kind is sc.RANGE:
                chars |= {chr(c) for c in range(arg[0], arg[1] + 1)}
            elif kind is sc.CATEGORY:
                chars |= set('0123456789')
            else:
                raise ValueError(kind)
        return chars, False
    if op is sc.BRANCH:
        chars, empty = set(), False
        for branch in av[1]:
            found, can_be_empty = first(branch)
            chars |= found
            empty |= can_be_empty
        return chars, empty
    if op is sc.SUBPATTERN:
        return first(av[-1])
    if op in (sc.MAX_REPEAT, sc.MIN_REPEAT):
        found, empty = first(av[2])
        return found, empty or av[0] == 0
    if op is sc.AT:
        return set(), True
    raise ValueError(op)


def branches(pattern):
    tree = sp.parse(pattern)
    if len(tree) == 1 and tree[0][0] is sc.BRANCH:
        return [list(b) for b in tree[0][1][1]]
    return [list(tree)]


def eligible(code, regions):
    lengths = set()
    for region in regions:
        meta = PhoneMetadata.metadata_for_region_or_calling_code(code, region)
        if meta.national_prefix != '0' or '0' in first(list(sp.parse(meta.general_desc.national_number_pattern)))[0]:
            return None
        possible = set(meta.general_desc.possible_length)
        lengths |= possible
        if meta.national_prefix_for_parsing not in (None, '0'):
            for branch in branches(meta.national_prefix_for_parsing):
                if branch == [(sc.LITERAL, ord('0'))] or '0' not in first(branch)[0]:
                    continue
                low, high = sp.SubPattern(sp.State(), branch).getwidth()
                if branch[-1][0] is sc.AT and low == high and all(low != 1 + n for n in possible):
                    continue
                return None
    for region in regions:
        if region == '001':
            continue
        for kind in TYPES:
            example = phonenumbers.example_number_for_type(region, kind)
            if example is None or example.country_code != code:
                continue
            nsn = phonenumbers.national_significant_number(example)
            parsed = phonenumbers.parse('0' + nsn, region)
            if (phonenumbers.national_significant_number(parsed) != nsn or not phonenumbers.is_valid_number(parsed)
                    or len(nsn) not in lengths):
                return None
    # E.164: at most 15 digits with the calling code; akdbx needs 4 or more.
    return sorted(n for n in lengths if 4 <= n <= 14 and len(str(code)) + n <= 15)


def main():
    rows = {code: eligible(code, regions) for code, regions in sorted(COUNTRY_CODE_TO_REGION_CODE.items())}
    print(f'# Generated by tools/trunk_zero_table.py from phonenumbers {phonenumbers.__version__}.')
    print('TRUNK_ZERO = {')
    line = '   '
    for code, lengths in rows.items():
        if lengths is None:
            continue
        item = f" '{code}': '{' '.join(map(str, lengths))}',"
        if len(line) + len(item) > 116:
            print(line)
            line = '   '
        line += item
    print(line)
    print('}')
    for code, lengths in rows.items():
        if lengths is not None:
            print('#', code, ' '.join(COUNTRY_CODE_TO_REGION_CODE[code]))


if __name__ == '__main__':
    main()
